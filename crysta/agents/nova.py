from __future__ import annotations

from .base import Agent


class Nova(Agent):
    id, name = "nova", "NOVA"
    description = "Coding and development: project explorer, editor, terminal, error explanation, run/test controls and logs; code generation needs a local model."
    system_instruction = ("You are Nova, a careful software engineer. Understand existing code before changing it. Prefer small, "
                          "verifiable changes. Never claim you edited or ran anything unless a tool did. Give complete, runnable code.")
    permitted_tools = frozenset({"project_inspect", "explain_error", "files_list", "files_read", "files_write", "project_commands", "logs_tail", "offline_search", "llm_chat", "llm_status"})

    NO_LLM = ("Writing or redesigning code needs a language model, and none is connected. What I can do offline: "
              "'inspect project <folder>', explain an error message if you paste it, and explain how to run things. "
              "To enable code generation, install Ollama (ollama.com) and run: ollama pull qwen2.5-coder:1.5b")

    def do_code(self, sub, ctx):
        answer = self.llm_answer(ctx, sub.text)
        if answer:
            return self.ok(answer, limitations=["Generated by a local model and NOT saved or run. Review before use; ask me to write it to a file if you want."])
        return self.partial(self.NO_LLM, limitations=["No language model connected."])

    def do_project(self, sub, ctx):
        info = self.tool(ctx, "project_inspect", path=sub.args.get("path") or "~")
        ext = ", ".join(f"{e} ×{c}" for e, c in info["top_extensions"]) or "none"
        txt = (f"Project at {info['root']}: {info['files_seen']} files. Main types: {ext}. "
               f"Detected: {', '.join(info['detected']) or 'nothing recognisable'}.")
        if info.get("npm_scripts"):
            txt += f" npm scripts: {', '.join(info['npm_scripts'])}."
        return self.ok(txt, data=info, limitations=["Scan limited to 3 folder levels and ~5000 files."])

    def do_error(self, sub, ctx):
        r = self.tool(ctx, "explain_error", text=sub.args.get("text") or sub.text)
        if r["matched"]:
            return self.ok(r["meaning"] + "\n" + "\n".join(f"{i}. {s}" for i, s in enumerate(r["steps"], 1)),
                           limitations=["Matched against a built-in list of common errors; your case may differ."])
        answer = self.llm_answer(ctx, "Explain this error and how to fix it:\n" + sub.text)
        if answer:
            return self.ok(answer, limitations=["Written by a local model; double-check before running commands."])
        return self.partial("I don't recognise that error from my built-in list. Paste the last 5 lines and the command you ran, "
                            "or connect a local model for deeper help.", limitations=["No language model connected."])

    def do_howto(self, sub, ctx):
        hits = self.tool(ctx, "offline_search", query="how to run start install local web app python", k=1)
        answer = self.llm_answer(ctx, sub.text)
        if answer:
            return self.ok(answer, limitations=["Written by a local model; verify commands before running."])
        if hits:
            return self.ok(hits[0]["text"], sources=[{"title": hits[0]["source"], "url": "", "note": "local knowledge file"}])
        return self.partial("Tell me which project and I'll inspect its folder to find the right run command.")
